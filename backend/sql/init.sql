-- Idempotent schema + seed script. Safe to run on every app startup.

CREATE TABLE IF NOT EXISTS checklist_items (
  id      TEXT PRIMARY KEY,
  label   TEXT NOT NULL,
  checked BOOLEAN NOT NULL,
  source  TEXT NOT NULL CHECK (source IN ('Calendar', 'Email', 'Reminder', 'Manual', 'Voice'))
);

-- Allow voice-created to-dos (backend/python/voice/daemon.py) alongside the
-- original sources -- idempotent: safe to re-run even though it's a plain
-- DROP+ADD rather than an IF-NOT-EXISTS form (no such form exists for CHECK).
ALTER TABLE checklist_items DROP CONSTRAINT IF EXISTS checklist_items_source_check;
ALTER TABLE checklist_items ADD CONSTRAINT checklist_items_source_check
  CHECK (source IN ('Calendar', 'Email', 'Reminder', 'Manual', 'Voice'));

