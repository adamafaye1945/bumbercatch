CREATE TABLE IF NOT EXISTS emails (
  id      TEXT PRIMARY KEY,
  account TEXT NOT NULL CHECK (account IN ('Personal', 'Work')),
  sender  TEXT NOT NULL,
  unread  BOOLEAN NOT NULL,
  subject TEXT NOT NULL,
  preview TEXT NOT NULL,
  body    TEXT NOT NULL
);

-- Real Outlook data now populates this table via the Microsoft Graph sync
-- (backend/src/outlook/sync.ts) -- add the column it needs and discard the
-- old fake seed rows (their IDs never collide with real Graph message IDs).
ALTER TABLE emails ADD COLUMN IF NOT EXISTS received_at TIMESTAMPTZ;
DELETE FROM emails WHERE id IN ('e1', 'e2', 'e3', 'e4');

CREATE TABLE IF NOT EXISTS notifications (
  id         TEXT PRIMARY KEY,
  source     TEXT NOT NULL,
  message    TEXT NOT NULL,
  read       BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Real notifications are now generated by backend rules (backend/src/notifications/rules.ts)
-- in response to actual events (new email, a Garmin metric drop, a missed reminder) --
-- discard the old fake seed rows and the free-text timestamp column they used.
ALTER TABLE notifications DROP COLUMN IF EXISTS timestamp;
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS read BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT now();
DELETE FROM notifications WHERE id IN ('n1', 'n2', 'n3', 'n4', 'n5');

